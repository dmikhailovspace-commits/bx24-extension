import assert from 'node:assert/strict';
import {createTodoWorker} from './lib/todo-worker-harness.mjs';
const worker=createTodoWorker(),scope={portalHost:'portal.test',userId:'7'};
let operation=0;
const save=(id,baseRevision,changes)=>worker.request('todo.save',scope,{id,baseRevision,changes,operationId:`op-${++operation}`});
await assert.rejects(worker.request('todo.list',scope,{},'other.test'),/origin/);
await assert.rejects(worker.request('todo.list',{...scope,userId:'0'}),/numeric/);
const [a,b]=await Promise.all([save('todo-one',0,{title:'  Первая   задача  '}),save('todo-two',0,{title:'Вторая',dueDate:'2026-10-22',task:{taskId:'101',title:'Задача 101'}})]);
assert.equal(a.item.title,'Первая задача');
assert.equal((await worker.request('todo.list',scope)).items.length,2,'parallel creates must both survive');
assert.equal((await worker.request('todo.list',{...scope,userId:'8'})).items.length,0);
assert.equal((await worker.request('todo.list',{...scope,portalHost:'other.test'})).items.length,0);
const raced=await Promise.allSettled([save('todo-one',1,{title:'Новое название'}),save('todo-one',1,{done:true})]);
assert.equal(raced.filter(row=>row.status==='fulfilled').length,1);
assert.equal(raced.find(row=>row.status==='rejected').reason.code,'todo_conflict');
const done=await save('todo-two',b.item.revision,{done:true});assert.ok(done.item.doneAt);
const reopened=await save('todo-two',done.item.revision,{done:false});assert.equal(reopened.item.doneAt,0);
const deleted=await save('todo-two',reopened.item.revision,{deleted:true});
assert.equal((await worker.request('todo.list',scope)).items.length,1);
await assert.rejects(save('todo-two',reopened.item.revision,{title:'stale resurrection'}),{code:'todo_conflict'});
const restored=await save('todo-two',deleted.item.revision,{deleted:false});assert.equal(restored.item.deletedAt,0);
const payload={id:'todo-two',baseRevision:restored.item.revision,operationId:'stable-retry',changes:{note:'Детали'}};
const first=await worker.request('todo.save',scope,payload),retry=await worker.request('todo.save',scope,payload);
assert.deepEqual(first,retry,'retry must not create another revision');
const steps=[{id:'step-one',title:'  Собрать   материалы ',done:false},{id:'step-two',title:'Проверить',done:true}];
const checklist=await save('todo-two',first.item.revision,{steps});
assert.equal(checklist.item.steps[0].title,'Собрать материалы');
const kept=await save('todo-two',checklist.item.revision,{note:'Новая заметка'});
assert.deepEqual(kept.item.steps,checklist.item.steps,'unrelated edits retain subtasks');
await assert.rejects(save('todo-two',checklist.item.revision,{steps:[]}),{code:'todo_conflict'});
for (const steps of [[{id:'invalid',title:'',done:false}],[{id:'step-one',title:'One',done:'false'}],Array(2).fill({id:'step-same',title:'Duplicate',done:false}),Array.from({length:101},(_,i)=>({id:`step-${1000+i}`,title:'Too many',done:false}))]) {
  await assert.rejects(save('todo-two',kept.item.revision,{steps}),{code:'todo_invalid'});
}
await assert.rejects(save('invalid-date',0,{title:'Bad',dueDate:'2026-02-30'}),{code:'todo_invalid'});
await assert.rejects(save('invalid-task',0,{title:'Bad',task:{taskId:'chat55'}}),{code:'todo_invalid'});
await assert.rejects(save('invalid-title',0,{title:' '.repeat(5)}),{code:'todo_invalid'});
const before=structuredClone(worker.data);worker.failWrite(true);
await assert.rejects(save('todo-three',0,{title:'Не записано'}));assert.deepEqual(worker.data,before);worker.failWrite(false);
const restarted=createTodoWorker(worker.data);
assert.deepEqual(await restarted.request('todo.list',scope),await worker.request('todo.list',scope));
console.log('PASS todo repository: scoped persistence, concurrent writers, revisions, tombstones, undo, retry and storage failure');
